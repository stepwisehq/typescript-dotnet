#nullable disable
using TypeScript.Scanner;
using static TypeScript.DiagnosticPrinting.PrinterUtilities;
namespace TypeScript.DiagnosticPrinting;
internal sealed class NameGenerator
{
    private const int tempFlagsAuto = 0, tempFlagsCountMask = 0x0fffffff, tempFlags_i = 0x10000000;
    internal EmitContext Context;
    internal Func<string, bool, bool> IsFileLevelUniqueNameInCurrentFile;
    internal Func<Node, string> GetTextOfNode;
    private Dictionary<ulong, string> nodeIdToGeneratedName, nodeIdToGeneratedPrivateName;
    private Dictionary<uint, string> autoGeneratedIdToGeneratedName;
    private NameGenerationScope nameGenerationScope, privateNameGenerationScope;
    private HashSet<string> generatedNames;
    private sealed class NameGenerationScope
    {
        internal NameGenerationScope next;
        internal int tempFlags;
        internal Dictionary<string, int> formattedNameTempFlags;
        internal HashSet<string> reservedNames;
    }
    internal void PushScope(bool reuseTempVariableScope)
    {
        privateNameGenerationScope = new() { next = privateNameGenerationScope };
        if (!reuseTempVariableScope) nameGenerationScope = new() { next = nameGenerationScope };
    }
    internal void PopScope(bool reuseTempVariableScope)
    {
        if (privateNameGenerationScope != null) privateNameGenerationScope = privateNameGenerationScope.next;
        if (!reuseTempVariableScope && nameGenerationScope != null) nameGenerationScope = nameGenerationScope.next;
    }
    private ref NameGenerationScope getScope(bool privateName) => ref (privateName ? ref privateNameGenerationScope : ref nameGenerationScope);
    private int getTempFlags(bool privateName) => getScope(privateName)?.tempFlags ?? tempFlagsAuto;
    private void setTempFlags(bool privateName, int flags)
    { ref var scope = ref getScope(privateName); scope ??= new(); scope.tempFlags = flags; }
    private int getTempFlagsForFormattedName(bool privateName, string key)
    {
        var scope = getScope(privateName);
        return scope?.formattedNameTempFlags?.TryGetValue(key, out var flags) == true ? flags : tempFlagsAuto;
    }
    private void setTempFlagsForFormattedName(bool privateName, string key, int flags)
    {
        ref var scope = ref getScope(privateName); scope ??= new(); scope.formattedNameTempFlags ??= new(StringComparer.Ordinal); scope.formattedNameTempFlags[key] = flags;
    }
    private void reserveName(string name, bool privateName, bool scoped, bool temp)
    {
        ref var scope = ref getScope(privateName); scope ??= new();
        if (privateName || scoped) { scope.reservedNames ??= new(StringComparer.Ordinal); scope.reservedNames.Add(name); }
        else if (!temp) { generatedNames ??= new(StringComparer.Ordinal); generatedNames.Add(name); }
    }
    internal string GenerateName(Node name)
    {
        if (Context != null && Context.autoGenerate?.TryGetValue(name, out var info) == true)
        {
            if (info.Flags.IsNode()) return generateNameForNodeCached(Context.GetNodeForGeneratedName(name), Ast.IsPrivateIdentifier(name), info.Flags, info.Prefix, info.Suffix);
            if (autoGeneratedIdToGeneratedName?.TryGetValue(info.Id, out var generated) == true) return generated;
            autoGeneratedIdToGeneratedName ??= new(); generated = makeName(name); autoGeneratedIdToGeneratedName[info.Id] = generated; return generated;
        }
        return GetTextOfNode(name);
    }
    private string generateNameForNodeCached(Node node, bool privateName, GeneratedIdentifierFlags flags, string prefix, string suffix)
    {
        ulong id = Ast.GetNodeId(node);
        ref var cache = ref (privateName ? ref nodeIdToGeneratedPrivateName : ref nodeIdToGeneratedName); cache ??= new();
        if (cache.TryGetValue(id, out var name)) return name;
        name = generateNameForNode(node, privateName, flags, prefix, suffix); cache[id] = name; return name;
    }
    private string generateNameForNode(Node node, bool privateName, GeneratedIdentifierFlags flags, string prefix, string suffix)
    {
        switch (node.Kind)
        {
            case Kind.Identifier: case Kind.PrivateIdentifier:
                return makeUniqueName(GetTextOfNode(node), null, flags.IsOptimistic(), flags.IsReservedInNestedScopes(), privateName, prefix, suffix);
            case Kind.ModuleDeclaration: case Kind.EnumDeclaration:
                if (privateName || prefix.Length > 0 || suffix.Length > 0) throw new InvalidOperationException("Generated name for a module or enum cannot be private and may have neither a prefix nor suffix");
                return generateNameForModuleOrEnum(node);
            case Kind.ImportDeclaration: case Kind.JSImportDeclaration: case Kind.ExportDeclaration:
                if (privateName || prefix.Length > 0 || suffix.Length > 0) throw new InvalidOperationException("Generated name for an import or export cannot be private and may have neither a prefix nor suffix");
                return generateNameForImportOrExportDeclaration(node);
            case Kind.FunctionDeclaration: case Kind.ClassDeclaration:
                if (privateName || prefix.Length > 0 || suffix.Length > 0) throw new InvalidOperationException("Generated name for a class or function declaration cannot be private and may have neither a prefix nor suffix");
                var name = node.Name();
                // Preserve the pinned condition, including its nil-context panic when reached.
                if (name != null && !(Context == null && Context.HasAutoGenerateInfo(name))) return generateNameForNode(name, false, flags, "", "");
                return generateNameForExportDefault();
            case Kind.ExportAssignment:
                if (privateName || prefix.Length > 0 || suffix.Length > 0) throw new InvalidOperationException("Generated name for an export assignment cannot be private and may have neither a prefix nor suffix");
                return generateNameForExportDefault();
            case Kind.ClassExpression:
                if (privateName || prefix.Length > 0 || suffix.Length > 0) throw new InvalidOperationException("Generated name for a class expression cannot be private and may have neither a prefix nor suffix");
                return generateNameForClassExpression();
            case Kind.MethodDeclaration: case Kind.GetAccessor: case Kind.SetAccessor:
                return generateNameForMethodOrAccessor(node, privateName, prefix, suffix);
            case Kind.ComputedPropertyName:
                return makeTempVariableName(tempFlagsAuto, true, privateName, prefix, suffix);
            default: return makeTempVariableName(tempFlagsAuto, false, privateName, prefix, suffix);
        }
    }
    private string generateNameForModuleOrEnum(Node node)
    {
        var name = GetTextOfNode(node.Name());
        return isUniqueLocalName(name, node) ? name : makeUniqueName(name, null, false, false, false, "", "");
    }
    private string generateNameForImportOrExportDeclaration(Node node)
    {
        var expression = Ast.GetExternalModuleName(node); var baseName = "module";
        if (Ast.IsStringLiteral(expression)) baseName = makeIdentifierFromModuleName(expression.Text());
        return makeUniqueName(baseName, null, false, false, false, "", "");
    }
    private string generateNameForExportDefault() => makeUniqueName("default", null, false, false, false, "", "");
    private string generateNameForClassExpression() => makeUniqueName("class", null, false, false, false, "", "");
    private string generateNameForMethodOrAccessor(Node node, bool privateName, string prefix, string suffix) => Ast.IsIdentifier(node.Name())
        ? generateNameForNodeCached(node.Name(), privateName, GeneratedIdentifierFlags.None, prefix, suffix)
        : makeTempVariableName(tempFlagsAuto, false, privateName, prefix, suffix);
    private string makeName(Node name)
    {
        if (Context != null && Context.autoGenerate?.TryGetValue(name, out var info) == true)
        {
            switch (info.Flags.Kind())
            {
                case GeneratedIdentifierFlags.Auto: return makeTempVariableName(tempFlagsAuto, info.Flags.IsReservedInNestedScopes(), Ast.IsPrivateIdentifier(name), info.Prefix, info.Suffix);
                case GeneratedIdentifierFlags.Loop:
                    if (!Ast.IsIdentifier(name)) throw new InvalidOperationException("Expected identifier");
                    return makeTempVariableName(tempFlags_i, info.Flags.IsReservedInNestedScopes(), false, info.Prefix, info.Suffix);
                case GeneratedIdentifierFlags.Unique:
                    return makeUniqueName(name.Text(), info.Flags.IsFileLevel() ? IsFileLevelUniqueNameInCurrentFile : null, info.Flags.IsOptimistic(), info.Flags.IsReservedInNestedScopes(), Ast.IsPrivateIdentifier(name), info.Prefix, info.Suffix);
            }
        }
        return GetTextOfNode(name);
    }
    private string makeTempVariableName(int flags, bool reservedInNestedScopes, bool privateName, string prefix, string suffix)
    {
        int tempFlags; string key = ""; bool simple = prefix.Length == 0 && suffix.Length == 0;
        if (simple) tempFlags = getTempFlags(privateName);
        else
        {
            key = FormatGeneratedName(privateName, prefix, "", suffix); if (privateName) key = ensureLeadingHash(key);
            tempFlags = getTempFlagsForFormattedName(privateName, key);
        }
        if (flags != 0 && (tempFlags & flags) == 0)
        {
            string fullName = FormatGeneratedName(privateName, prefix, "_i", suffix);
            if (isUniqueName(fullName, privateName))
            {
                tempFlags |= flags; reserveName(fullName, privateName, reservedInNestedScopes, true);
                if (simple) setTempFlags(privateName, tempFlags); else setTempFlagsForFormattedName(privateName, key, tempFlags);
                return fullName;
            }
        }
        for (;;)
        {
            int count = tempFlags & tempFlagsCountMask; tempFlags = unchecked(tempFlags + 1);
            if (count != 8 && count != 13)
            {
                string name = count < 26 ? "_" + (char)('a' + count) : "_" + (count - 26).ToString(System.Globalization.CultureInfo.InvariantCulture);
                string fullName = FormatGeneratedName(privateName, prefix, name, suffix);
                if (isUniqueName(fullName, privateName))
                {
                    reserveName(fullName, privateName, reservedInNestedScopes, true);
                    if (simple) setTempFlags(privateName, tempFlags); else setTempFlagsForFormattedName(privateName, key, tempFlags);
                    return fullName;
                }
            }
        }
    }
    private string makeUniqueName(string baseName, Func<string, bool, bool> checkFn, bool optimistic, bool scoped, bool privateName, string prefix, string suffix)
    {
        baseName = removeLeadingHash(baseName);
        if (optimistic)
        {
            string fullName = FormatGeneratedName(privateName, prefix, baseName, suffix);
            if (checkUniqueName(fullName, privateName, checkFn)) { reserveName(fullName, privateName, scoped, false); return fullName; }
        }
        if (baseName.Length > 0 && baseName[^1] != '_') baseName += "_";
        for (int i = 1;; i = unchecked(i + 1))
        {
            string fullName = FormatGeneratedName(privateName, prefix, baseName + i.ToString(System.Globalization.CultureInfo.InvariantCulture), suffix);
            if (checkUniqueName(fullName, privateName, checkFn)) { reserveName(fullName, privateName, scoped, false); return fullName; }
        }
    }
    internal string MakeFileLevelOptimisticUniqueName(string name) => makeUniqueName(name, IsFileLevelUniqueNameInCurrentFile, true, false, false, "", "");
    private bool checkUniqueName(string name, bool privateName, Func<string, bool, bool> checkFn) => checkFn != null ? checkFn(name, privateName) : isUniqueName(name, privateName);
    private static Node nextContainer(Node node) => node.LocalsContainerData()?.NextContainer;
    private static bool isUniqueLocalName(string name, Node container)
    {
        var node = container;
        while (node != null && Ast.IsNodeDescendantOf(node, container) && node.LocalsContainerData() != null)
        {
            var locals = node.Locals();
            if (locals != null && locals.TryGetValue(name, out var local) && (local.Flags & (SymbolFlags.Value | SymbolFlags.ExportValue | SymbolFlags.Alias)) != 0) return false;
            node = nextContainer(node);
        }
        return true;
    }
    private bool isUniqueName(string name, bool privateName) => (IsFileLevelUniqueNameInCurrentFile == null || IsFileLevelUniqueNameInCurrentFile(name, privateName)) && !isReservedName(name, privateName);
    private bool isReservedName(string name, bool privateName)
    {
        var scope = getScope(privateName); if (generatedNames?.Contains(name) == true) return true;
        while (scope != null) { if (scope.reservedNames?.Contains(name) == true) return true; scope = scope.next; }
        return false;
    }
}
