#!/usr/bin/env python3
"""Translate pinned numeric AST binder enums; fail on unfamiliar declarations."""
import re
from pathlib import Path
UP=Path('upstream/TypeScript/tsc/internal/ast');OUT=Path('src/TypeScript.Scanner/Ast')
for name,source in [('SymbolFlags','symbolflags.go'),('FlowFlags','flow.go'),('FunctionFlags','functionflags.go')]:
 text=(UP/source).read_text();block=re.search(r'const \((.*?)\n\)',text,re.S)[1];rows=[]
 for line in block.splitlines():
  line=line.split('//')[0].strip()
  if not line:continue
  m=re.fullmatch(name+r'(\w+)(?:\s+'+name+r')?\s*=\s*(.+)',line)
  if not m:raise ValueError((source,line))
  key,value=m.groups();value=re.sub(name+r'(\w+)',r'\1',value).replace('^','~')
  value=re.sub(r'\b1\s*<<\s*(\d+)',r'(1u << \1)',value)
  rows.append('    '+key+' = '+value+',')
 header='// Copyright (c) Microsoft Corporation. All rights reserved.\n// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.\n// Modified C# port, upstream fed0bf24149fb1ed36039212648bafdafc1ea10e.\n// Port of tsc/internal/ast/'+source+'; generated by tools/generate-binder-enums.py.\nnamespace TypeScript.Scanner;\n'
 # Flow flags remain in their flow.go counterpart with graph classes appended manually.
 dest=OUT/(name+'.cs')
 if name=='FlowFlags':dest=OUT/'Flow.cs'
 suffix=''
 if dest.exists() and '// BEGIN MANUAL ' in dest.read_text():suffix='\n// BEGIN MANUAL '+dest.read_text().split('// BEGIN MANUAL ',1)[1]
 dest.write_text(header+'[Flags]\npublic enum '+name+' : uint\n{\n'+'\n'.join(rows)+'\n}\n'+suffix)
