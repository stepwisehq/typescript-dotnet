#!/usr/bin/env python3
"""Emit exact pinned message records referenced by accepted scanner/parser/binder and selected checker."""
from pathlib import Path
import re,json
up=Path('upstream/TypeScript/tsc/internal');dest=Path('src/TypeScript.Scanner/Diagnostics/DiagnosticsGenerated.cs')
required=set(re.findall(r'static readonly Message (\w+)',dest.read_text()))
for folder in ['scanner','parser','binder']:
 for file in (up/folder).glob('*.go'):
  if not file.name.endswith('_test.go'):required.update(re.findall(r'diagnostics\.(\w+)',file.read_text()))
for file in Path('src/TypeScript.Scanner/Checker').glob('*.cs'):
 required.update(re.findall(r'Diagnostics\.(\w+)',file.read_text()))
rows=[];found=set()
for name,body in re.findall(r'^var (\w+) = &Message\{(.*)\}$',(up/'diagnostics/diagnostics_generated.go').read_text(),re.M):
 if name not in required:continue
 fields=dict(re.findall(r'(\w+):\s*("(?:[^"\\]|\\.)*"|\w+)',body));found.add(name)
 for field in ['code','category','key','text']:
  if field not in fields:raise ValueError((name,field))
 category=fields['category'].removeprefix('Category');key=json.loads(fields['key']);text=json.loads(fields['text'])
 flags=', '+fields.get('reportsUnnecessary','false')+', '+fields.get('reportsDeprecated','false')
 rows.append('    public static readonly Message '+name+' = new('+fields['code']+', DiagnosticCategory.'+category+', '+json.dumps(key,ensure_ascii=False)+', '+json.dumps(text,ensure_ascii=False)+flags+');')
old=set(re.findall(r'static readonly Message (\w+)',dest.read_text()))
if old-found:raise ValueError(('old metadata lost',old-found))
header='// Copyright (c) Microsoft Corporation. All rights reserved.\n// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.\n// Modified C# port, upstream fed0bf24149fb1ed36039212648bafdafc1ea10e.\n// Port of tsc/internal/diagnostics/diagnostics_generated.go.\n// Generated by tools/generate-required-diagnostics.py; scanner/parser/binder/selected-checker dependency slice.\nnamespace TypeScript.Scanner;\n'
dest.write_text(header+'public static class Diagnostics\n{\n'+'\n'.join(rows)+'\n}\n')
print('Messages:',len(rows),'new:',len(found-old))
