#!/usr/bin/env python3
"""Reproduce static Core option models/descriptors from the locked upstream source.

No runtime reflection or option-default evaluation. The hand-written accessors remain
in CompilerOptions.cs; this generator owns only OptionsGenerated.cs.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'upstream/TypeScript/tsc/internal/core/options_generated.go'
TARGET = ROOT / 'src/TypeScript.Scanner/Core/OptionsGenerated.cs'
LOCKED_SHA = '133eb1f0d134b192e82ec97254e5202e26c05f654dc77ec14cfd9ec7b110f6af'


def generate():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != LOCKED_SHA:
        raise SystemExit('Locked core/options_generated.go source drift')
    text = raw.decode()
    lines = [
        '// Copyright (c) Microsoft Corporation. All rights reserved.',
        '// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.',
        '// Modified C# port of tsc/internal/core/options_generated.go at fed0bf24149fb1ed36039212648bafdafc1ea10e.',
        '// Generated by tools/configuration-generate-options.py. DO NOT EDIT.',
        '// Source SHA256: ' + LOCKED_SHA,
        'using TypeScript.Collections;', 'using System.Runtime.CompilerServices;',
        'namespace TypeScript.Scanner;', '',
    ]
    for name in ['ModuleDetectionKind','ModuleKind','ModuleResolutionKind','NewLineKind','ScriptTarget','JsxEmit']:
        body = re.search(r'type ' + name + r' int32\s+const \((.*?)\n\)', text, re.S).group(1)
        lines.extend(['public enum ' + name, '{'])
        for suffix, value in re.findall(r'\b' + name + r'(\w+)\s+' + name + r' = (\w+)', body):
            if value.startswith(name): value = value[len(name):]
            lines.append(f'    {suffix} = {value},')
        lines.extend(['}', ''])
    lines.extend([
        'public struct PluginImport : IEquatable<PluginImport>', '{',
        '    private string? name;', '    public string Name { readonly get => name ?? ""; set => name = value; }',
        '    public readonly bool Equals(PluginImport other) => Name == other.Name;',
        '    public override readonly bool Equals(object? other) => other is PluginImport plugin && Equals(plugin);',
        '    public override readonly int GetHashCode() => StringComparer.Ordinal.GetHashCode(Name);', '}', '',
        '// Static stored-field descriptors are authored AOT-safe observation/JSON metadata.',
        '// Read observes the actual field and never computes an effective option default.',
        'public sealed record OptionFieldDescriptor<T>(string Name, string JsonName, string GoType, Func<T, object?> Read);', '',
    ])
    typemap = {'string':'string', '*int':'StrongBox<long>?', '[]string':'List<string>?',
              '*collections.OrderedMap[string, []string]':'OrderedMap<string, List<string>?>?',
              '[]PluginImport':'List<PluginImport>?', '[]tspath.RootedDirectoryPath':'List<RootedDirectoryPath>?'}
    all_fields = {}
    for name in ['CompilerOptions', 'TypeAcquisition', 'BuildOptions']:
        body = re.search(r'type ' + name + r' struct \{(.*?)\n\}', text, re.S).group(1)
        fields = re.findall(r'^\s*(\w+)\s+([^`\n]+?)\s+`json:"([^,"]+)[^"]*"`', body, re.M)
        all_fields[name] = fields
        lines.extend(['public sealed partial class ' + name, '{'])
        for field, typ, json in fields:
            typ = typ.strip()
            cs = typemap.get(typ, typ.removeprefix('tspath.'))
            init = ' = ""' if cs == 'string' else ''
            lines.append(f'    public {cs} {field}{init};')
        if name == 'CompilerOptions':
            lines.extend(['', '    // Original Clone is a shallow copy, including list/map header identities.',
                          '    public CompilerOptions Clone() => new()', '    {'])
            lines += [f'        {field} = {field},' for field, _, _ in fields]
            lines.extend(['    };', '', '    public bool Equals(CompilerOptions? other)', '    {',
                          '        if (ReferenceEquals(this, other)) return true;',
                          '        if (other == null) return false;', '        return'])
            checks=[]
            for field, typ, json in fields:
                typ = typ.strip()
                if typ.startswith('[]'):
                    check = f'(({field} == null) == (other.{field} == null) && OptionModelEquality.SlicesEqual({field}, other.{field}))'
                elif typ.startswith('*collections.'):
                    check = f'OrderedMaps.EqualFunc({field}, other.{field}, (a, b) => (a == null) == (b == null) && OptionModelEquality.SlicesEqual(a, b))'
                elif typ == '*int':
                    check = f'(ReferenceEquals({field}, other.{field}) || {field} != null && other.{field} != null && {field}.Value == other.{field}.Value)'
                else:
                    check = f'{field} == other.{field}'
                checks.append('            ' + check)
            lines.append(' &&\n'.join(checks) + ';')
            lines.append('    }')
        lines.extend(['}', ''])
    lines.extend(['public static class OptionFields', '{'])
    for name, fields in all_fields.items():
        lines.extend([f'    public static readonly IReadOnlyList<OptionFieldDescriptor<{name}>> {name} = new OptionFieldDescriptor<{name}>[]', '    {'])
        lines += [f'        new("{field}", "{json}", "{typ.strip()}", options => options.{field}),' for field, typ, json in fields]
        lines.extend(['    };', ''])
    lines.extend(['}', '', 'internal static class OptionModelEquality', '{',
                  '    // Go slices.Equal treats nil and empty as equal; callers explicitly add nil checks where required.',
                  '    internal static bool SlicesEqual<T>(List<T>? a, List<T>? b) =>',
                  '        (a?.Count ?? 0) == (b?.Count ?? 0) && (a == null || b == null || a.SequenceEqual(b));', '}', '',
                  'public static class GeneratedOptionEnums', '{',
                  '    public static readonly IReadOnlyDictionary<ModuleKind, ModuleResolutionKind> ModuleKindToModuleResolutionKind = new Dictionary<ModuleKind, ModuleResolutionKind>',
                  '    { [ModuleKind.Node16] = ModuleResolutionKind.Node16, [ModuleKind.NodeNext] = ModuleResolutionKind.NodeNext };',
                  '    public static string String(this ModuleResolutionKind value) => value switch', '    {',
                  '        ModuleResolutionKind.Unknown => throw new InvalidOperationException("should not use zero value of ModuleResolutionKind"),',
                  '        ModuleResolutionKind.Classic => "Classic", ModuleResolutionKind.Node10 => "Node10",',
                  '        ModuleResolutionKind.Node16 => "Node16", ModuleResolutionKind.NodeNext => "NodeNext",',
                  '        ModuleResolutionKind.Bundler => "Bundler",',
                  '        _ => throw new InvalidOperationException("unhandled case in ModuleResolutionKind.String"),', '    };',
                  '    public static string String(this JsxEmit value) => value switch', '    {',
                  '        JsxEmit.None => throw new InvalidOperationException("should not use zero value of JsxEmit"),',
                  '        JsxEmit.Preserve => "preserve", JsxEmit.React => "react", JsxEmit.ReactNative => "react-native",',
                  '        JsxEmit.ReactJSX => "react-jsx", JsxEmit.ReactJSXDev => "react-jsxdev",',
                  '        _ => throw new InvalidOperationException("unhandled case in JsxEmit.String"),', '    };', '}', ''])
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != output:
            raise SystemExit('OptionsGenerated.cs does not match source generation')
    else:
        TARGET.write_text(output)
