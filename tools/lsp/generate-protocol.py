#!/usr/bin/env python3
"""Generate closed LSP DTO declarations from the pinned committed Go model.

The committed Go file, including its required/null tags, is authoritative. No
network schema fetch or reflection metadata is required by the generated runtime.
"""
from pathlib import Path
import re
import json
import hashlib

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'upstream/TypeScript/tsc/internal/lsp/lsproto/lsp_generated.go'
DEST = ROOT / 'src/TypeScript.Scanner/Lsp/Protocol'
text = SOURCE.read_text()
outputs = {}
def stage(path, content):
    outputs[path] = content


def block_end(start):
    depth = 0
    quote = None
    escaped = False
    i = start
    while i < len(text):
        ch = text[i]
        if quote:
            if quote == '`':
                if ch == '`': quote = None
            elif escaped: escaped = False
            elif ch == '\\': escaped = True
            elif ch == quote: quote = None
        elif text.startswith('//', i):
            i = text.find('\n', i)
            if i < 0: raise ValueError('unterminated comment')
            continue
        elif ch in '\"\'`': quote = ch
        elif ch == '{': depth += 1
        elif ch == '}':
            depth -= 1
            if depth == 0: return i + 1
        i += 1
    raise ValueError('unterminated Go type')

types = {}
for match in re.finditer(r'^type (\w+) ([^\n]+)', text, re.M):
    name, definition = match.groups()
    line = text.count('\n', 0, match.start()) + 1
    if re.match(r'struct\s*\{', definition):
        start = text.index('{', match.start())
        end = block_end(start)
        fields = []
        for raw in text[start+1:end-1].splitlines():
            raw = raw.strip()
            if not raw or raw.startswith('//'): continue
            field = re.fullmatch(r'(\w+)\s+(.+?)(?:\s+`([^`]+)`)?', raw)
            if not field: raise ValueError(f'{name}:{raw}')
            field_name, field_type, tags = field.groups()
            tags = tags or ''
            json_tag = re.search(r'json:"([^"]+)"', tags)
            lsp_tag = re.search(r'lsp:"([^"]+)"', tags)
            fields.append(dict(name=field_name, csName='CommandValue' if name == 'Command' and field_name == 'Command' else field_name, type=field_type.strip(), json=json_tag.group(1) if json_tag else None, lsp=lsp_tag.group(1) if lsp_tag else ''))
        types[name] = dict(kind='struct', fields=fields, line=line)
    elif definition.startswith('= '): types[name] = dict(kind='alias', type=definition[2:].strip(), line=line)
    else: types[name] = dict(kind='scalar', type=definition.strip(), line=line)

constants = {}
for name, spec in types.items():
    if spec['kind'] == 'scalar':
        constants[name] = [(m.group(1), m.group(2)) for m in re.finditer(r'^\s*(\w+)\s+' + re.escape(name) + r'\s*=\s*([^\n/]+)', text, re.M)]

# Preserve aliases as C# compilation aliases: Go aliases have no runtime owner
# or identity distinct from their target. DTO fields resolve to the same target.
value_structs = {'Position', 'Range', 'BooleanOrEmptyObject', 'BooleanOrClientSemanticTokensRequestFullDelta'} | {n for n in types if n.startswith('Resolved')}
def mapped(go_type):
    if go_type.startswith('*'):
        target = go_type[1:]
        while target in types and types[target]['kind'] == 'alias': target = types[target]['type']
        if target == 'any': return 'ProtocolPointer<object?>?'
        inner = mapped(go_type[1:])
        return inner if inner.endswith('?') else inner + '?'
    if go_type.startswith('[2]'): return 'Slice<' + mapped(go_type[3:]) + '>'
    if go_type.startswith('[]'): return 'Slice<' + mapped(go_type[2:]) + '>'
    if go_type.startswith('map['):
        close = go_type.index(']')
        return 'ProtocolMap<' + ('ByteStringKey' if go_type[4:close] == 'string' else mapped(go_type[4:close])) + ', ' + mapped(go_type[close+1:]) + '>'
    if go_type in types and types[go_type]['kind'] == 'alias': return mapped(types[go_type]['type'])
    primitives = {'string':'ByteStringValue', 'bool':'bool', 'uint32':'uint', 'int32':'int', 'float64':'double', 'any':'object?', 'uint':'uint', 'int':'int', 'struct{}':'EmptyProtocolObject'}
    if go_type in primitives: return primitives[go_type]
    if go_type not in types and go_type not in {'DocumentUri', 'Method', 'URI', 'Null', 'NoParams'}: raise ValueError('Unmapped Go type: ' + go_type)
    return go_type

def ident(name):
    return '@' + name if name in {'String','Integer','Range'} else name

header = '// Copyright (c) Microsoft Corporation. All rights reserved.\n// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.\n// Generated by tools/lsp/generate-protocol.py from pinned lsp_generated.go; DO NOT EDIT.\n#nullable enable\n'
lines = [header, 'using TypeScript.Scanner;', 'namespace TypeScript.Lsp.Protocol;', '', 'internal struct EmptyProtocolObject { }', '']
for name, spec in types.items():
    if spec['kind'] == 'alias': continue
    lines.append(f'// lsp_generated.go:{spec["line"]}')
    if spec['kind'] == 'scalar':
        base = spec['type']
        if base == 'string':
            lines.extend([f'internal readonly {"partial " if name == "CodeActionKind" else ""}struct {name}(ByteStringValue value) : IEquatable<{name}>', '{', '    internal readonly ByteStringValue Value = value;', f'    public bool Equals({name} other) => Value.EqualsValue(other.Value);', f'    public override bool Equals(object? other) => other is {name} typed && Equals(typed);', '    public override int GetHashCode() => ByteStringKey.FromValue(Value).GetHashCode();', f'    public static bool operator ==({name} left, {name} right) => left.Equals(right);', f'    public static bool operator !=({name} left, {name} right) => !left.Equals(right);'])
            for constant, value in constants[name]:
                suffix = constant.removeprefix(name)
                lines.append(f'    internal static readonly {name} {suffix} = new(ByteStringValue.FromString({value.strip()}));')
            lines.append('}')
        elif base in {'uint32', 'int32'}:
            lines.extend([f'internal enum {name} : {mapped(base)}', '{'])
            for constant, value in constants[name]:
                lines.append(f'    {constant.removeprefix(name)} = {value.strip()},')
            lines.append('}')
        else: raise ValueError(f'Unmapped scalar {name}: {base}')
    else:
        is_value = name in value_structs or not spec['fields']
        interfaces = []
        for method, interface in [('TextDocumentURI', 'IHasTextDocumentURI'), ('TextDocumentPosition', 'IHasTextDocumentPosition'), ('GetLocation', 'IHasLocation'), ('GetLocations', 'IHasLocations')]:
            if re.search(r'^func \(\w+ \*?' + name + r'\) ' + method + r'\(', text, re.M): interfaces.append(interface)
        suffix = ' : ' + ', '.join(interfaces) if interfaces else ''
        lines.extend([f'internal {"partial struct" if is_value else "sealed partial class"} {name}{suffix}', '{'])
        for field in spec['fields']:
            cs = mapped(field['type'])
            init = ''
            # Embedded Go objects always have a zero-value owner. Optional Go
            # pointers remain null and never create speculative owners.
            target = field['type']
            if not is_value and target in types and types[target]['kind'] == 'struct' and target not in value_structs and types[target]['fields']:
                init = ' = new()'
            lines.append(f'    public {cs} {ident(field["csName"])}{init};')
        lines.append('}')
    lines.append('')
DEST.mkdir(parents=True, exist_ok=True)
stage(DEST / 'Models.Generated.cs', '\n'.join(lines))
manifest = dict(source='upstream/TypeScript/tsc/internal/lsp/lsproto/lsp_generated.go', sha256=hashlib.sha256(SOURCE.read_bytes()).hexdigest(), types=types, constants=constants)
stage(ROOT / 'tools/lsp/model-schema.json', json.dumps(manifest, indent=2) + '\n')
print(f'Generated {len(types)} source-defined type declarations; alias targets resolved without new runtime owners.')

# The generator also preserves all capability resolver bodies. Extension
# methods permit a null receiver, matching Go's nil-aware pointer methods.
resolvers = [header, 'using TypeScript.Scanner;', 'namespace TypeScript.Lsp.Protocol;', '', 'internal static class ProtocolCapabilities', '{']
resolver_count = 0
for match in re.finditer(r'^func \(v \*(\w+)\) (resolve|Resolve)\(\) (\w+) \{', text, re.M):
    owner, method, result = match.groups()
    start = text.index('{', match.start())
    end = block_end(start)
    body = text[start+1:end-1]
    literal = re.search(r'return ' + result + r'\{\s*(.*?)\s*\}\s*$', body[body.rfind('return ' + result + '{'):], re.S)
    if not literal or not re.search(r'if v == nil \{\s*return ' + result + r'\{\}\s*\}', body):
        raise ValueError(f'Unrecognized capability resolver: {owner}')
    resolvers.extend([f'    // lsp_generated.go:{text.count(chr(10), 0, match.start()) + 1}', f'    internal static {result} Resolve(this {owner}? value)', '    {', '        if (value is null)', '            return default;', f'        return new {result}', '        {'])
    for entry in literal.group(1).splitlines():
        entry = entry.strip()
        if not entry: continue
        field = re.fullmatch(r'(\w+):\s*(.+),', entry)
        if not field: raise ValueError(f'Unrecognized resolver entry: {owner}:{entry}')
        name, expression = field.groups()
        if re.fullmatch(r'derefOr\(v\.\w+\)', expression):
            expression = expression[8:-1].replace('v.', 'value.') + ' ?? default'
        elif re.fullmatch(r'v\.\w+\.resolve\(\)', expression):
            expression = expression.replace('v.', 'value.').replace('.resolve()', '.Resolve()')
        elif re.fullmatch(r'v\.\w+', expression): expression = expression.replace('v.', 'value.')
        else: raise ValueError(f'Unrecognized resolver expression: {owner}:{expression}')
        resolvers.append(f'            {ident(name)} = {expression},')
    resolvers.extend(['        };', '    }', ''])
    resolver_count += 1
resolvers.append('}')
stage(DEST / 'Capabilities.Generated.cs', '\n'.join(resolvers) + '\n')
print(f'Generated all {resolver_count} source-defined nil-aware capability resolvers.')

members = [header, 'using TypeScript.Scanner;', 'namespace TypeScript.Lsp.Protocol;', '']
member_count = 0
for match in re.finditer(r'^func \((\w+) \*?(\w+)\) (TextDocumentURI|TextDocumentPosition|GetLocation|GetLocations|Compare)\(([^)]*)\) ([^{\n]+)\{', text, re.M):
    receiver, owner, method, parameters, result = match.groups()
    start = text.index('{', match.start())
    end = block_end(start)
    body = text[start+1:end-1].strip()
    result = result.strip()
    is_value = owner in value_structs or not types[owner].get('fields')
    members.extend([f'// lsp_generated.go:{text.count(chr(10), 0, match.start()) + 1}', f'internal {"partial struct" if is_value else "sealed partial class"} {owner}', '{'])
    if method != 'Compare':
        members.append(f'    public {mapped(result)} {method}()')
        members.append('    {')
        if body == f'return {receiver}':
            # A Go value receiver copies Location. Its C# reference owner must
            # return the same shallow field copy, not its own mutable identity.
            if owner != 'Location': raise ValueError('Unexpected value receiver return: ' + owner)
            members.append('        return new Location { Uri = Uri, Range = Range };')
        elif re.fullmatch(r'return ' + receiver + r'\.\w+(?:\.\w+)?', body):
            expression = body[len('return ' + receiver + '.'):]
            members.append(f'        return {expression};')
        else:
            literal = re.fullmatch(r'return Location\{(.*?)\}', body, re.S)
            if not literal: raise ValueError('Unrecognized projection: ' + owner + '.' + method)
            members.extend(['        return new Location', '        {'])
            for raw in literal.group(1).splitlines():
                raw = raw.strip()
                if not raw: continue
                field = re.fullmatch(r'(\w+):\s*' + receiver + r'\.(\w+),', raw)
                if not field: raise ValueError('Unrecognized location field: ' + raw)
                members.append(f'            {field.group(1)} = {field.group(2)},')
            members.append('        };')
        members.extend(['    }', '}', ''])
    else:
        members.extend([f'    internal int Compare({owner} other)', '    {'])
        if owner == 'Position':
            members.extend(['        int comparison = Line.CompareTo(other.Line);', '        return comparison != 0 ? comparison : Character.CompareTo(other.Character);'])
        elif owner == 'Range':
            members.extend(['        int comparison = Start.Compare(other.Start);', '        return comparison != 0 ? comparison : End.Compare(other.End);'])
        elif owner == 'TextEdit':
            members.extend(['        int comparison = Range.Compare(other.Range);', '        return comparison != 0 ? comparison : ByteStringKey.FromValue(NewText).CompareTo(ByteStringKey.FromValue(other.NewText));'])
        else: raise ValueError('Unrecognized Compare owner: ' + owner)
        members.extend(['    }', '}', ''])
    member_count += 1
stage(DEST / 'Members.Generated.cs', '\n'.join(members) + '\n')
print(f'Generated all {member_count} source-defined document/location/comparison projections.')

# Numeric enum names are the exact generated known-value names; open unknown
# values retain Go's Type(decimal) fallback rather than .NET Enum.ToString.
enums = [header, 'using System.Globalization;', 'using TypeScript.Scanner;', 'namespace TypeScript.Lsp.Protocol;', '', 'internal static class ProtocolEnumNames', '{']
enum_count = 0
for name, spec in types.items():
    if spec['kind'] != 'scalar' or spec['type'] not in {'uint32', 'int32'}: continue
    if not re.search(r'^func \(e ' + name + r'\) String\(', text, re.M): continue
    enums.extend([f'    // lsp_generated.go:{spec["line"]}: generated String known-value table.', f'    internal static ByteStringValue String(this {name} value) => value switch', '    {'])
    seen_values = set()
    for constant, value in constants[name]:
        value = value.strip()
        if value in seen_values: raise ValueError('Ambiguous enum name: ' + name)
        seen_values.add(value)
        suffix = constant.removeprefix(name)
        enums.append(f'        {name}.{suffix} => ByteStringValue.FromString("{suffix}"),')
    enums.extend([f'        _ => ByteStringValue.FromString("{name}(" + (({mapped(spec["type"])})value).ToString(CultureInfo.InvariantCulture) + ")"),', '    };', ''])
    enum_count += 1
if enum_count != 30: raise ValueError('Numeric enum source inventory changed: ' + str(enum_count))
enums.append('}')
stage(DEST / 'EnumNames.Generated.cs', '\n'.join(enums) + '\n')
print(f'Generated all {enum_count} source-defined numeric enum String functions.')

# Method has its actual scalar owner in lsp.go, outside generated model types.
# Its complete generated constant set still belongs to this source family.
methods = [header, 'using TypeScript.Scanner;', 'namespace TypeScript.Lsp.Protocol;', '', 'internal readonly partial struct Method', '{']
method_constants = list(re.finditer(r'^\s*(Method\w+)\s+Method\s*=\s*("[^"\n]*")', text, re.M))
for constant in method_constants:
    name, value = constant.groups()
    methods.append(f'    internal static readonly Method {name.removeprefix("Method")} = new(ByteStringValue.FromString({value}));')
methods.append('}')
stage(DEST / 'Methods.Generated.cs', '\n'.join(methods) + '\n')
print(f'Generated all {len(method_constants)} source-defined method constants.')

# Finish source analysis before replacing any production output. Each replacement
# is atomic; integration builds are coordinated around the full generation pass.
for path, content in outputs.items():
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(content)
for path in outputs:
    path.with_suffix(path.suffix + '.tmp').replace(path)
