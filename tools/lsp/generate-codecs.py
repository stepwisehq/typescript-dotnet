#!/usr/bin/env python3
"""Reproduce closed pinned protocol codecs in an ignored staging directory.

The modules run beside their generated intermediate fragments. No fragment enters
production compilation; promotion uses the complete assembled files only.
"""
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
STAGE = ROOT / 'artifacts/language-services/codec-generation'
MODULES = Path(__file__).parent / 'codecs'
STAGE.mkdir(parents=True, exist_ok=True)
for source in sorted(MODULES.glob('*.py')):
    shutil.copyfile(source, STAGE / source.name)
# Root shapes must exist before field helpers traverse their complete consumers.
for name in ('extract-codec-methods', 'root-descriptors', 'generate-codecs',
             'assemble-codecs', 'model-facades', 'materialize-protocol-tests',
             'materialize-protocol-decode-tests', 'protocol-test-equality'):
    subprocess.run([sys.executable, str(STAGE / (name + '.py'))], cwd=ROOT, check=True)
print(STAGE)
header = '''// Copyright (c) Microsoft Corporation. All rights reserved.
// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.
// Generated by tools/lsp/generate-codecs.py from pinned lsproto Go sources.
#nullable enable
using TypeScript.Scanner;
namespace TypeScript.Lsp.Protocol;
'''
(STAGE / 'RootDescriptors.Generated.cs').write_text(header + 'internal static partial class ProtocolCodec\n{\n' + (STAGE / 'root-descriptors.cs').read_text() + '\n}\n')
(STAGE / 'MethodInfos.Generated.cs').write_text(header + 'internal readonly partial struct Method\n{\n' + (STAGE / 'method-infos.cs').read_text() + '\n}\n')
