#!/usr/bin/env python3
"""Reproduce the complete static TsOptions generated option-function counterpart.

Field cases/merge order/build-info selection/serialization order and comparison expressions
come from the locked source. Finite syntax checks reject unknown generated forms.
"""
import argparse
import hashlib
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'upstream/TypeScript/tsc/internal/tsoptions/options_generated.go'
TARGET=ROOT/'src/TypeScript.Scanner/TsOptions/OptionsGenerated.cs'
LOCKED_SHA='333f1dd771e53e6bd0976dae450c5b05bac18994140e4d365645d7cbabe069dd'


def functions(text):
    starts=list(re.finditer(r'^func (\w+)\(',text,re.M))
    return {m.group(1):text[m.start():starts[i+1].start() if i+1<len(starts) else len(text)] for i,m in enumerate(starts)}


def fields():
    text=(ROOT/'upstream/TypeScript/tsc/internal/core/options_generated.go').read_text()
    body=re.search(r'type CompilerOptions struct \{(.*?)\n\}',text,re.S).group(1)
    return {name:typ.strip() for name,typ in re.findall(r'^\s*(\w+)\s+([^`\n]+?)\s+`json:',body,re.M)}


def expr(text, types):
    text=text.replace('core.TSUnknown','Tristate.Unknown').replace('core.TSTrue','Tristate.True').replace('core.TSFalse','Tristate.False').replace('nil','null')
    # Go named string path types use empty-string zero values; managed wrappers use default.
    for name, typ in types.items():
        if typ.startswith('tspath.'):
            text=re.sub(r'(\b(?:options|oldOptions|newOptions|sourceOptions|targetOptions)\.'+name+r'\s*(?:!=|==)\s*)""',r'\1default',text)
    return text


def generate():
    raw=SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=LOCKED_SHA:raise SystemExit('Locked options source drift')
    fs=functions(raw.decode());types=fields()
    out=['// Copyright (c) Microsoft Corporation. All rights reserved.',
         '// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.',
         '// Modified C# port of tsc/internal/tsoptions/options_generated.go at fed0bf24149fb1ed36039212648bafdafc1ea10e.',
         '// Generated by tools/configuration-generate-tsoptions.py. DO NOT EDIT.',
         '// Source SHA256: '+LOCKED_SHA,'using TypeScript.Collections;', 'using TypeScript.Scanner;',
         'namespace TypeScript.TsOptions;', '', 'public static partial class TsOptions', '{']
    def emit(line=''):out.append('    '+line if line else '')
    emit('internal static bool parseCompilerOptions(string key, object? value, CompilerOptions allOptions)')
    emit('{');emit('    var option = CommandLineCompilerOptionsMap.Get(key);');emit('    if (option != null) key = option.Name;')
    emit('    switch (key)');emit('    {')
    parser=fs['parseCompilerOptions']
    cases=re.findall(r'\tcase (.*?):\n(.*?)(?=\tcase |\tdefault:)',parser,re.S)
    for names,body in cases:
        for key in re.findall(r'"([^"]+)"',names):emit('        case "'+key+'":')
        if names=='"plugins"':
            emit('            if (value is List<object?> plugins) allOptions.Plugins = plugins.Select(plugin => plugin is OrderedMap<string, object?> map ? new PluginImport { Name = ParseString(map.GetOrZero("name")) } : default).ToList();')
        elif names=='"lib"':emit('            allOptions.Lib = value is List<string> libs ? libs : ParseStringArray(value);')
        else:
            match=re.fullmatch(r'\s*allOptions\.(\w+) = (.*?)\s*',body,re.S)
            if not match:raise ValueError('Unhandled parse case '+names)
            field,value=match.groups()
            m=re.fullmatch(r'floatOrInt32ToFlag\[core\.(\w+)\]\(value\)',value)
            if m:
                typ=m.group(1);value=f'floatOrInt32ToFlag<{typ}>(value, static flag => ({typ})flag)'
            elif value=='tspath.ToSourceMapLocation(ParseString(value))':value='TsPath.ToSourceMapLocation(parsePathText(value))'
            emit('            allOptions.'+field+' = '+value+';')
        emit('            break;')
    emit('        default: return false;');emit('    }');emit('    return true;');emit('}');emit()
    emit('internal static parsedCompilerOptions getDefaultCompilerOptions(RootedFilePath configFileName)')
    emit('{');emit('    var options = configFileName != default && configFileName.BaseNameValue().EqualsBytes("jsconfig.json"u8) ? new CompilerOptions { AllowJs = Tristate.True, NoEmit = Tristate.True, SkipLibCheck = Tristate.True, MaxNodeModuleJsDepth = new(2) } : new CompilerOptions();')
    emit('    return new parsedCompilerOptions { CompilerOptions = options, unresolvedPaths = new() };');emit('}');emit()
    emit('internal static TypeAcquisition getDefaultTypeAcquisition(RootedFilePath configFileName) => new() { Enable = configFileName != default && configFileName.BaseNameValue().EqualsBytes("jsconfig.json"u8) ? Tristate.True : Tristate.Unknown };');emit()
    for function,cls,mapname in [('ParseTypeAcquisition','TypeAcquisition',None),('ParseBuildOptions','BuildOptions','BuildNameMap')]:
        emit(f'public static void {function}(string key, object? value, {cls}? allOptions)');emit('{')
        emit('    if (value == null || allOptions == null) return;')
        if mapname:emit(f'    var option = {mapname}.Get(key);');emit('    if (option != null) key = option.Name;')
        emit('    switch (key)');emit('    {')
        for key,field,call in re.findall(r'\tcase "([^"]+)":\s*allOptions\.(\w+) = ([^\n]+)',fs[function]):
            emit(f'        case "{key}": allOptions.{field} = {call}; break;')
        emit('    }');emit('}');emit()
    for function in ['CompilerOptionsAffectSemanticDiagnostics','CompilerOptionsAffectDeclarationPath','CompilerOptionsAffectEmit']:
        body=re.search(r'\treturn (oldOptions\..*?)\n\}',fs[function],re.S).group(1)
        emit(f'public static bool {function}(CompilerOptions? oldOptions, CompilerOptions? newOptions)');emit('{')
        emit('    if (ReferenceEquals(oldOptions, newOptions)) return false;');emit('    if (oldOptions == null || newOptions == null) return true;')
        emit('    return '+expr(body,types).replace('\n\t\t','\n        ')+';');emit('}');emit()
    emit('public static void ForEachCompilerOptionAffectingBuildInfo(CompilerOptions options, Action<CommandLineOption, object?> fn)');emit('{')
    items=re.findall(r'\tif (.*?) \{\s*fn\((.*?)\)\s*\}',fs['ForEachCompilerOptionAffectingBuildInfo'],re.S)
    if len(items)!=67:raise ValueError('Build-info selection changed '+str(len(items)))
    for condition,args in items:emit('    if ('+expr(condition,types)+') fn('+args.replace('.Get(','.Get(').replace('),',')!,')+');')
    emit('}');emit()
    emit('internal static void mergeCompilerOptionFields(CompilerOptions targetOptions, CompilerOptions sourceOptions, HashSet<string>? explicitNullFields)');emit('{')
    merges=re.findall(r'\tif explicitNullFields.Has\("([^"]+)"\) \{\s*targetOptions\.(\w+) = (.*?)\s*\} else if (.*?) \{\s*targetOptions\.\2 = sourceOptions\.\2\s*\}',fs['mergeCompilerOptionFields'],re.S)
    if len(merges)!=132:raise ValueError('Merge field selection changed '+str(len(merges)))
    for key,field,zero,condition in merges:
        if types[field].startswith('tspath.') and zero=='""':zero='default'
        zero=expr(zero,types)
        emit(f'    if (explicitNullFields?.Contains("{key}") == true) targetOptions.{field} = {zero};')
        emit('    else if ('+expr(condition,types)+f') targetOptions.{field} = sourceOptions.{field};')
    emit('}');emit()
    emit('internal static void handleOptionConfigDirTemplateSubstitution(parsedCompilerOptions? compilerOptions, RootedDirectoryPath basePath)');emit('{')
    emit('    if (compilerOptions == null) return;');emit('    OrderedMap<string, List<string>?>? paths = null;')
    emit('    if (compilerOptions.CompilerOptions.Paths != null) foreach (var (key, value) in compilerOptions.CompilerOptions.Paths.Entries())');emit('    {')
    emit('        var substitution = getSubstitutedStringArrayWithConfigDirTemplate(value, basePath);');emit('        if (substitution != null)');emit('        {')
    emit('            if (paths == null) compilerOptions.CompilerOptions.Paths = paths = compilerOptions.CompilerOptions.Paths.Clone();');emit('            paths.Set(key, substitution);');emit('        }');emit('    }')
    emit('    if (compilerOptions.unresolvedPaths != null) foreach (var (key, item) in compilerOptions.unresolvedPaths)');emit('    {')
    emit('        object? value = CommandLineCompilerOptionsMap.Get(key)!.Kind == CommandLineOptionKind.List ? parsePathTexts(item)?.Select(path => (object?)getSubstitutedPathWithConfigDirTemplate(path, basePath)).ToList() : getSubstitutedPathWithConfigDirTemplate(parsePathText(item), basePath);')
