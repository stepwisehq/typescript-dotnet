#!/usr/bin/env python3
"""Generate syntax-only C# payloads/factories from the pinned Go AST schema.

Go embedded syntax bases become interfaces; their fields are flattened into the
payload classes. Node aliases and list aliases retain their common Go identity.
Binder-owned Symbol/Flow/Locals state is emitted separately from syntax metadata.
Checker state and general transformation methods remain excluded.
This generator fails on unrecognized factory statements rather than omitting them.
"""
from pathlib import Path
import re, sys
UP = Path('upstream/TypeScript/tsc/internal/ast')
OUT = Path(sys.argv[1]) if len(sys.argv) == 2 else Path('src/TypeScript.Scanner/Ast')
if len(sys.argv) > 2:raise ValueError('usage: generate-ast.py [output-directory]')
HEADER = '''// Copyright (c) Microsoft Corporation. All rights reserved.
// Licensed under the Apache License, Version 2.0. See licenses/TypeScript-LICENSE.txt.
// Modified C# port, upstream fed0bf24149fb1ed36039212648bafdafc1ea10e.
'''
def write(name, source, body):
    (OUT/name).write_text(HEADER + '// Port of tsc/internal/ast/'+source+'.\n// Generated by tools/generate-ast.py; parser/binder dependency slice.\n#nullable disable\nnamespace TypeScript.Scanner;\n\n'+body)
s = (UP/'ast_generated.go').read_text()
manual = (UP/'ast.go').read_text()
aliases = dict(re.findall(r'^\s*(\w+)\s*=\s*(NodeList|Node|Kind)\b', s+(UP/'kind_generated.go').read_text()+manual,re.M))
bound_fields = {'Symbol','LocalSymbol','Locals','NextContainer','FlowNode','EndFlowNode','ReturnFlowNode','FallthroughFlowNode'}
excluded = {'facts','TypeArgumentsForInference','Links','Type','TypeArguments'}
# Type and TypeArguments are syntax fields except checker-owned SyntheticExpression.Type.
excluded -= {'Type','TypeArguments'}
base_excluded = {'CompositeBase','NodeBase'}
structs={}
for name,body in re.findall(r'type (\w+) struct \{(.*?)\n\}',s,re.S):
    if name=='NodeFactory': continue
    embeds=[];fields=[]
    for line in body.splitlines():
        line=line.split('//')[0].strip()
        if not line:continue
        m=re.fullmatch(r'(\w+)\s+(.+)',line)
        if m:
            n,t=m.groups()
            if n not in excluded and not (name=='SyntheticExpression' and n=='Type'):fields.append((n,t))
        elif re.fullmatch(r'\w+',line):embeds.append(line)
        else:raise ValueError((name,line))
    structs[name]=(embeds,fields)
for n in re.findall(r'type (\w+) struct ?\{\}', s): structs[n]=([],[])
bases={n for n in structs if n.endswith('Base')}
concrete=[n for n in structs if n not in bases and n != 'SyntheticExpression']
def ancestors(n):
    out=[]
    for e in structs[n][0]:
        if e in base_excluded:continue
        if e not in structs:raise ValueError((n,e))
        if e not in out:out.append(e)
        for x in ancestors(e):
            if x not in out:out.append(x)
    return out
def fields(n):
    out=[]
    for e in structs[n][0]:
        if e not in base_excluded:
            for f in fields(e):
                if f not in out:out.append(f)
    out.extend(structs[n][1])
    return out
# Managed compatibility for Go JSDoc []string text descriptors. Keep only these
# four payloads borrowed internally; public mutable List<string> APIs stay intact.
jsdoc_fragment_models = {'JSDocText', 'JSDocLink', 'JSDocLinkPlain', 'JSDocLinkCode'}
# Go Text/RawText strings can borrow source storage; the public raw string API
# remains a projection/setter, and generated clones preserve the value header.
borrowed_text_models = {'StringLiteral', 'TemplateMiddle', 'Identifier', 'RegularExpressionLiteral', 'TemplateTail', 'NoSubstitutionTemplateLiteral', 'BigIntLiteral', 'JsxText', 'PrivateIdentifier', 'NumericLiteral', 'TemplateHead'}
def composite(n):
    return n=='CompositeBase' or any(composite(e) for e in structs.get(n,([],[]))[0])
def typ(t):
    t=t.strip()
    if t == '[]*Node': return 'Slice<Node>'
    if t.startswith('[]'):return 'List<'+typ(t[2:])+'>'
    t=t.lstrip('*')
    if t in aliases:return aliases[t]
    if t.startswith('core.'):return t[5:]
    return {'uint8':'byte','uint32':'uint','int32':'int','any':'object'}.get(t,t)
def cname(n):return '@'+n if n in {'namespace','event','base','params','default','operator','fixed','ref','object','string','internal'} else n
def expr(t):
    t=t.replace('node.', 'this.').replace('f.', 'this.').replace('nil','null').replace('core.Same(', 'Ast.SameSyntaxSlice(')
    t=re.sub(r'\bKind(\w+)',r'Kind.\1',t)
    for p in ['TokenFlags','NodeFlags','ModifierFlags']:
        t=re.sub(r'\b'+p+r'(\w+)',p+r'.\1',t)
    t=re.sub(r'(?<![\w@])(?:operator|namespace)(?!\w)', lambda m:'@'+m[0],t)
    return t
def funcs(source):
    for m in re.finditer(r'^func (?:\((\w+) \*(\w+)\) )?(\w+)\(([^\n]*)\)([^\n{]*) \{',source,re.M):
        i=m.end();depth=1
        while depth:
            if source[i]=='{':depth+=1
            elif source[i]=='}':depth-=1
            i+=1
        yield m.groups(),source[m.end():i-1].strip()
fs=list(funcs(s))
# Exact kind IDs including aliases.
k=(UP/'kind_generated.go').read_text();names=[]
for line in k.splitlines():
    m=re.fullmatch(r'\s*Kind(\w+)(?:\s+Kind\s*=\s*iota)?\s*(?://.*)?',line)
    if m:names.append(m[1])
ka=re.findall(r'\bKind(\w+)\s*=\s*Kind(\w+)',k)
write('KindGenerated.cs','kind_generated.go','public enum Kind : short\n{\n'+''.join(f'    {n} = {i},\n' for i,n in enumerate(names))+''.join(f'    {n} = {v},\n' for n,v in ka)+'}\n')
# Stringer uses canonical names rather than the runtime's arbitrary enum alias.
ks=(UP/'kind_stringer_generated.go').read_text()
blob=re.search(r'const _Kind_name = ("[^"]+")',ks)[1]
ix=re.search(r'var _Kind_index = .*?\{([^}]+)\}',ks)[1]
write('KindStringerGenerated.cs','kind_stringer_generated.go','public static class KindNames\n{\n    private const string Names = '+blob+';\n    private static readonly ushort[] Indexes = ['+ix+'];\n    public static string String(this Kind kind)\n    {\n        int index = (int)kind;\n        if (index < 0 || index >= Indexes.Length - 1) return "Kind(" + index.ToString(System.Globalization.CultureInfo.InvariantCulture) + ")";\n        return Names.Substring(Indexes[index], Indexes[index + 1] - Indexes[index]);\n    }\n}\n')
# Base contracts contain only syntax fields. Flattened properties preserve mutations.
# CLR payloads inherit the common Node header. Syntax fields that share a
# Node accessor name deliberately hide that nonvirtual forwarding member.
node_member_names = ['Arguments', 'Attributes', 'Body', 'Children', 'ClassName', 'Elements', 'Expression', 'ImportClause', 'Initializer', 'IsTypeOnly', 'Label', 'LocalSymbol', 'Locals', 'Members', 'ModuleSpecifier', 'Parameters', 'PostfixToken', 'Properties', 'PropertyName', 'QuestionDotToken', 'QuestionToken', 'RawText', 'Statement', 'Statements', 'Symbol', 'TagName', 'Text', 'TextValue', 'Type', 'TypeArguments', 'TypeExpression', 'TypeParameters']
def member_hiding(name): return 'new ' if name in node_member_names else ''
parts=['public interface INodeData\n{\n    Node AsNode();\n    Node Name();\n    ModifierList Modifiers();\n}\n']
for n in sorted(bases-base_excluded):
    parts.append('public interface '+n+' : INodeData\n{\n'+''.join('    '+typ(t)+' '+cname(f)+' { get; set; }\n' for f,t in fields(n))+'}\n')
for n in concrete:
    ff=fields(n); aa=ancestors(n)
    # Only the source CompositeBase embeds atomic facts; scalar payloads retain
    # no cache field. Both managed bases share the canonical Node identity.
    node_base = 'CompositeNodeData' if composite(n) else 'NodeData'
    parts.append('public sealed partial class '+n+' : '+node_base+''.join(', '+a for a in aa)+'\n{')
    for f,t in ff:
        ct=typ(t);initial=' = "";' if ct=='string' else ''
        if n in jsdoc_fragment_models and f == 'text':
            assert ct == 'List<string>', (n, f, ct)
            parts.append("""    // Managed JSDoc-only storage bridge; public list mutation remains visible.
    internal JSDocTextFragments TextFragments { get; private set; }
    public List<string> text
    {
        get => TextFragments?.AsList();
        set => TextFragments = JSDocTextFragments.FromStrings(value);
    }
    internal void SetTextFragments(JSDocTextFragments value) => TextFragments = value;""")
        elif n in borrowed_text_models and f in {'Text', 'RawText'}:
            assert ct == 'string', (n, f, ct)
            storage = 'textValue' if f == 'Text' else 'rawTextValue'
            parts.append('    private ByteStringValue '+storage+';\n    internal '+member_hiding(f+'Value')+'ByteStringValue '+f+'Value { get => '+storage+'.Snapshot(); set => '+storage+' = value; }\n    public '+member_hiding(f)+'string '+f+' { get => '+storage+'.Project(); set => '+storage+' = ByteStringValue.FromString(value); }')
        else:
            parts.append('    public '+member_hiding(f)+ct+' '+cname(f)+' { get; set; }'+initial)
    if any(f=='name' for f,t in ff):parts.append('    public override Node Name() => name;')
    if any(f=='modifiers' for f,t in ff):parts.append('    public override ModifierList Modifiers() => modifiers;\n    public override void SetModifiers(ModifierList value) => modifiers = value;')
    child=next((b for (recv,rtype,fn,ps,rt),b in fs if rtype==n and fn=='ForEachChild'),None)
    if child:
        # These generated visitors contain only the ordered short-circuit return.
        assert child.startswith('return '),(n,child)
        ce=expr(child[7:]).replace('forEachChild_JSDocParameterOrPropertyTag(node,', 'Ast.ForEachChildJSDocParameterOrPropertyTag(this,').replace('visitNodeList(', 'Ast.VisitNodeList(').replace('visitModifiers(', 'Ast.VisitModifiers(').replace('visit(', 'Ast.Visit(').replace('visitNodes(', 'Ast.VisitNodes(')
        parts.append('    public override bool ForEachChild(Visitor v) => '+ce+';')
    clone=next((b for (recv,rtype,fn,ps,rt),b in fs if rtype==n and fn=='Clone'),None)
    if clone and n in jsdoc_fragment_models:
        args = 'this.TextFragments' if n == 'JSDocText' else 'this.name, this.TextFragments'
        parts.append('    public override Node Clone(NodeFactoryCoercible f) => Ast.CloneNode(f.AsNodeFactory().New'+n+'WithFragments('+args+'), this.AsNode(), f.AsNodeFactory().hooks);')
    elif clone:
        ce=expr(clone.replace('f.', 'cloneFactory.')).replace('cloneFactory.', 'f.').replace('cloneNode(', 'Ast.CloneNode(')
        if n in borrowed_text_models:
            ce = ce.replace('New'+n+'(', 'New'+n+'WithTextValue(').replace('this.Text', 'this.TextValue').replace('this.RawText', 'this.RawTextValue')
        if ce.startswith('return '):parts.append('    public override Node Clone(NodeFactoryCoercible f) => '+ce[7:]+';')
        else:
            ce=ce.replace('this.Kind.String()', 'this.Kind.ToString()')
            ce=re.sub(r'switch ([^\n{]+) \{',r'switch (\1) {',ce)
            ce=re.sub(r'panic\(([^\n]+)\)',r'throw new InvalidOperationException(\1)',ce)
            ce=re.sub(r'(?m)^(\s*(?:return |throw )[^\n]+)$',r'\1;',ce)
            parts.append('    public override Node Clone(NodeFactoryCoercible f)\n    {\n'+ce+'\n    }')
    visit_each=next((b for (recv,rtype,fn,ps,rt),b in fs if rtype==n and fn=='VisitEachChild'),None)
    if visit_each:
        if n in jsdoc_fragment_models:
            # JSDocText has no VisitEachChild source method; named link nodes do.
            assert n != 'JSDocText', n
            parts.append('    public override Node VisitEachChild(NodeVisitor v) => v.Factory.Update'+n+'WithFragments(this, v.visitNode(this.name), this.TextFragments);')
        elif n=='SyntaxList':
            parts.append('    public override Node VisitEachChild(NodeVisitor v) => v.Factory.UpdateSyntaxList(this, Ast.SameMapNodes(Children, v));')
        elif n=='JSDocTypeLiteral':
            parts.append('    public override Node VisitEachChild(NodeVisitor v) => v.Factory.UpdateJSDocTypeLiteral(this, Ast.SameMapNodes(JSDocPropertyTags, v), IsArrayType);')
        else:
            assert visit_each.startswith('return '),(n,visit_each)
            ve=expr(visit_each[7:]).replace('(node,', '(this,').replace('visitEachChild_JSDocParameterOrPropertyTag(', 'Ast.VisitEachChildJSDocParameterOrPropertyTag(')
            parts.append('    public override Node VisitEachChild(NodeVisitor v) => '+ve+';')
    parts.append('    public override string DataType() => \"'+n+'\";')
    parts.append('    public override IEnumerable<SyntaxField> SyntaxFields()\n    {')
    if ff:
        for f,t in ff:
            if f in bound_fields:continue
            ct=typ(t)
            ft={'Node':'node','NodeList':'list','ModifierList':'list','List<Node>':'nodes','Slice<Node>':'nodes','List<string>':'strings','string':'bytes','bool':'bool'}.get(ct,'number')
            parts.append('        yield return new SyntaxField("'+f+'", "'+ft+'", '+cname(f)+');')
    if not any(f not in bound_fields for f,t in ff):parts.append('        yield break;')
    parts.append('    }')
    parts.append('    public override IEnumerable<SyntaxField> BoundFields()\n    {')
    for f,t in ff:
        if f not in bound_fields:continue
        ct=typ(t);ft={'Symbol':'symbol','SymbolTable':'table','Node':'node','FlowNode':'flow'}[ct]
        parts.append('        yield return new SyntaxField("'+f+'", "'+ft+'", '+cname(f)+');')
    if not any(f in bound_fields for f,t in ff):parts.append('        yield break;')
    parts.append('    }\n}\n')
parts.append('public partial class NodeFactory\n{')
count=0
for (recv,rtype,fn,ps,rt),body in fs:
    if rtype!='NodeFactory' or not fn.startswith('New') or fn=='NewSyntheticExpression':continue
    args=[]
    for p in ps.split(','):
        if not p.strip():continue
        name,t=p.strip().split(' ',1);args.append(typ(t)+' '+cname(name))
    lines=[]
    for line in body.splitlines():
        line=line.strip()
        if not line or line.startswith('//'):continue
        if line.startswith('data :='):
            dtype=re.search(r'&?(\w+)\{\}',line)
            if dtype:dtype=dtype[1]
            else:
                arena=re.search(r'f\.(\w+)Arena\.New\(\)',line)[1]
                dtype=next(n for n in concrete if n.lower()==arena.lower())
            lines.append('var data = new '+dtype+'();')
        elif line.startswith('data.'):
            lines.append(expr(line)+';')
        elif line=='f.textCount++':lines.append('textCount++;')
        elif line.startswith('return f.newNode('):lines.append(expr(line)+';')
        elif line.startswith('node := f.newNode('):lines.append('var node = '+expr(line.split(':=',1)[1].strip())+';')
        elif line.startswith('node.Flags'):lines.append(expr(line).replace('this.Flags','node.Flags')+';')
        elif line=='return node':lines.append('return node;')
        else:raise ValueError((fn,line))
    if fn in {'NewSyntaxList', 'NewJSDocTypeLiteral'}:
        compat_args = [arg.replace('Slice<Node>', 'List<Node>') for arg in args]
        call_args = [arg.split(' ')[-1] for arg in args]
        position = next(i for i,arg in enumerate(args) if arg.startswith('Slice<Node>'))
        value = call_args[position]
        call_args[position] = value+' is null ? default(Slice<Node>) : Slice<Node>.FromArray('+value+'.ToArray())'
        parts.append('    public Node '+fn+'('+', '.join(compat_args)+') => '+fn+'('+', '.join(call_args)+');')
    parts.append('    public Node '+fn+'('+', '.join(args)+')\n    {\n'+''.join('        '+l+'\n' for l in lines)+'    }')
    count+=1
    if fn[3:] in borrowed_text_models:
        borrowed_args = [arg.replace('string ', 'ByteStringValue ', 1) if arg.startswith('string ') else arg for arg in args]
        borrowed_lines = [line.replace('data.Text =', 'data.TextValue =').replace('data.RawText =', 'data.RawTextValue =') for line in lines]
        parts.append('    // Go string-header bridge; initialize before OnCreate publication.\n    internal Node '+fn+'WithTextValue('+', '.join(borrowed_args)+')\n    {\n'+''.join('        '+line+'\n' for line in borrowed_lines)+'    }')
    if fn[3:] in jsdoc_fragment_models:
        model = fn[3:]
        borrowed_args = 'JSDocTextFragments text' if model == 'JSDocText' else 'Node name, JSDocTextFragments text'
        borrowed_lines = ['var data = new '+model+'();']
        if model != 'JSDocText': borrowed_lines.append('data.name = name;')
        borrowed_lines += ['data.SetTextFragments(text);', 'textCount++;', 'return this.newNode(Kind.'+model+', data);']
        parts.append('    // Managed JSDoc view bridge; assign before OnCreate publication.\n    internal Node '+fn+'WithFragments('+borrowed_args+')\n    {\n'+''.join('        '+l+'\n' for l in borrowed_lines)+'    }')
for (recv,rtype,fn,ps,rt),body in fs:
    if rtype!='NodeFactory' or not fn.startswith('Update') or fn=='UpdateSyntheticExpression':continue
    args=[]
    for p in ps.split(','):
        name,t=p.strip().split(' ',1);args.append(typ(t)+' '+cname(name))
    b=expr(body).replace('this.', 'node.').replace('node.New', 'this.New').replace('node.hooks', 'hooks')
    b=b.replace('updateNode(', 'Ast.UpdateNode(').replace('node.Kind.String()', 'node.Kind.ToString()')
    b=re.sub(r'if ([^\n]+) \{',r'if (\1) {',b)
    b=re.sub(r'switch ([^\n{]+) \{',r'switch (\1) {',b)
    b=re.sub(r'case ([^:]+):',lambda m:''.join('case '+v.strip()+':\n' for v in m[1].split(',')),b)
    b=re.sub(r'panic\(([^\n]+)\)',r'throw new InvalidOperationException(\1)',b)
    b=re.sub(r'(?m)^(\s*(?:return |throw )[^\n]+)$',r'\1;',b)
    if fn in {'UpdateSyntaxList', 'UpdateJSDocTypeLiteral'}:
        compat_args = [arg.replace('Slice<Node>', 'List<Node>') for arg in args]
        call_args = [arg.split(' ')[-1] for arg in args]
        position = next(i for i,arg in enumerate(args) if arg.startswith('Slice<Node>'))
        value = call_args[position]
        call_args[position] = value+' is null ? default(Slice<Node>) : Slice<Node>.FromArray('+value+'.ToArray())'
        parts.append('    public Node '+fn+'('+', '.join(compat_args)+') => '+fn+'('+', '.join(call_args)+');')
    parts.append('    public Node '+fn+'('+', '.join(args)+')\n    {\n'+''.join('        '+l+'\n' for l in b.splitlines())+'    }')
# Borrowed visitor updates retain the same source storage before any public
# projection. Public Update methods above keep source SameSyntaxSlice semantics.
for model in ['JSDocLink', 'JSDocLinkPlain', 'JSDocLinkCode']:
    parts.append('    internal Node Update'+model+'WithFragments('+model+' node, Node name, JSDocTextFragments text)\n    {\n        if (name != node.name || !ReferenceEquals(text, node.TextFragments))\n            return Ast.UpdateNode(this.New'+model+'WithFragments(name, text), node.AsNode(), hooks);\n        return node.AsNode();\n    }')
parts.append('}\npublic partial class Node\n{')
for n in concrete:parts.append('    public '+n+' As'+n+'() => this as '+n+' ?? ('+n+')data;')
parts.append('    public SourceFile AsSourceFile() => this as SourceFile ?? (SourceFile)data;')
parts.append('}\n')
# Generated kind predicates, mechanically preserve switches/range conditions.
parts.append('public static partial class Ast\n{')
for (recv,rtype,fn,ps,rt),body in fs:
    if recv or not fn.startswith('Is') or rt.strip()!='bool':continue
    if not re.fullmatch(r'\w+ \*(?:Node)|\w+ Kind',ps):continue
    if any(x in body for x in ['node.data','panic(','for ']):continue
    name,t=ps.split(' ',1);b=expr(body).replace('this.', 'node.')
    b=re.sub(r'switch (\w+\.\w+|\w+) \{',r'switch (\1) {',b)
    b=re.sub(r'case ([^:]+):',lambda m:''.join('case '+v.strip()+':\n' for v in m[1].split(',')),b)
    b=b.replace('return true','return true;').replace('return false','return false;')
    if 'switch ' not in b:b=b+';'
    parts.append('    public static bool '+fn+'('+typ(t)+' '+name+')\n    {\n'+''.join('        '+l+'\n' for l in b.splitlines())+'    }')
parts.append('}\n')
write('AstGenerated.cs','ast_generated.go','\n'.join(parts))
print(f'Generated {len(names)} kinds, {len(concrete)} payload classes, {count} factories.')
