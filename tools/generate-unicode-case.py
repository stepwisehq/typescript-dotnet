#!/usr/bin/env python3
"""Extract the Go 1.27.1 Unicode casing slice used by spelling suggestions.

Run tools/bootstrap-go.sh first, then this script. This generates the table only;
Runtime/UnicodeCase.cs preserves the lookup/fold algorithms separately.
"""
from pathlib import Path
import hashlib
import re

root = Path(__file__).resolve().parent.parent
source = root / 'tools/.cache/go/src/unicode/tables.go'
expected_sha = 'ac0e5d5d1b58ed4b02d7cb4a0085bdefbdb4f7aae6fadddbc9477f8463da8bd8'
source_bytes = source.read_bytes()
assert hashlib.sha256(source_bytes).hexdigest() == expected_sha, 'Unexpected Go Unicode tables'
text = source_bytes.decode()

def section(name):
    return re.search(r'var ' + name + r' = [^\n]+\{\n(.*?)\n\}', text, re.S)[1]

ranges = re.findall(r'\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+), d\{([^}]+)\}\}', section('_CaseRanges'))
orbits = re.findall(r'\{(0x[0-9A-Fa-f]+), (0x[0-9A-Fa-f]+)\}', section('caseOrbit'))
assert len(ranges) == 336 and len(orbits) == 94
version = re.search(r'const Version = "([^"]+)"', text)[1]
output = '''// Copyright 2009 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style license in licenses/Go-LICENSE.txt.
// Modified C# scanner-only port of Go 1.27.1 src/unicode/tables.go (Unicode %s).
// Generated by tools/generate-unicode-case.py; only CaseRanges and caseOrbit are copied.
namespace TypeScript.Scanner;

internal static partial class UnicodeCase
{
    private const int UpperLower = 0x110000;
    private static readonly (int Low, int High, int Upper, int Lower)[] CaseRanges =
    [
''' % version
for low, high, deltas in ranges:
    upper, lower, _ = deltas.split(', ')
    output += f'        ({low}, {high}, {upper}, {lower}),\n'
output += '''    ];
    private static readonly (int From, int To)[] CaseOrbit =
    [
'''
for a, b in orbits:
    output += f'        ({a}, {b}),\n'
output += '    ];\n}\n'
(root / 'src/TypeScript.Scanner/Runtime/UnicodeCaseTables.cs').write_text(output)
print(f'Generated {len(ranges)} case ranges and {len(orbits)} fold orbit entries (Unicode {version})')
